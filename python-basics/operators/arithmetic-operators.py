"""
+	Addition	    x + y
-	Subtraction	    x - y
*	Multiplication	x * y
/	Division	    x / y (returns a float)
%	Modulus	        x % y
**	Exponentiation	x ** y
//	Floor division	x // y (returns an integer)
"""
x = 15
y = 4

print(f"{x} + {y} =", x + y)
print(f"{x} - {y} =",x - y)
print(f"{x} × {y} =",x * y)
print(f"{x} ÷ {y} =",x / y)
print(f"{x} mod {y} =",x % y)
print(f"{x} ^ {y} =",x ** y)
print(f"{x} // {y} =",x // y)